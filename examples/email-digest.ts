// Ask a model for a report and write it as an email (HTML + text parts):
//   node examples/email-digest.ts "Weekly sales summary for a small bakery"
// Writes digest.html and digest.txt next to this file; sending is up to you.

import { writeFileSync } from "node:fs";
import { loadEnvFile } from "@vak/providers";
import { createVak } from "@vak/kit";

loadEnvFile(new URL("../.env", import.meta.url).pathname);
const vak = createVak({ model: process.env.VAK_MODEL ?? "ollama:qwen3.5:4b-mlx" });
const reply = await vak.ask(process.argv[2] ?? "A weekly summary for a small bakery: sales KPIs and the top products");
const mail = vak.email({ surface: reply.surfaces[0]?.id, footer: "Sample data, generated by vak." });
writeFileSync(new URL("digest.html", import.meta.url), mail.html);
writeFileSync(new URL("digest.txt", import.meta.url), mail.text);
console.log(`Subject: ${mail.subject}\nWrote examples/digest.html and examples/digest.txt`);

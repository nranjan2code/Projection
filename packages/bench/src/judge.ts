// Semantic judge: a model grades what the user would see (the text
// projection) against the scenario's intent. Optional and costed: it runs
// only when asked, and reports its token usage.

import { type JSONSchema, parseLenient, type Usage } from "@vak/core";
import type { Provider } from "@vak/providers";
import type { Judge } from "./runner.ts";

const SCHEMA: JSONSchema = {
  type: "object",
  properties: {
    score: { type: "integer", minimum: 1, maximum: 5 },
    reason: { type: "string" },
  },
  required: ["score", "reason"],
};

const SYSTEM = `You grade user interfaces generated by an AI assistant.
You see the user's request, what a good answer must achieve, and the interface as plain text
([Card], [Table], [Input] ... mark components; * marks required fields).
Score 1-5:
5 = fully achieves the intent with specific, plausible content and a usable layout
4 = achieves it with minor gaps
3 = partially achieves it; notable gaps or generic content
2 = mostly misses the intent
1 = wrong, empty or unusable
Reply with JSON only: {"score": <1-5>, "reason": "<one sentence>"}`;

export function modelJudge(provider: Provider, model: string, onUsage?: (u: Usage) => void): Judge {
  return async (scenario, finalText) => {
    const user = `Request: ${scenario.turns.map((t) => t.say ?? `[user ${t.act?.target === "form" ? "submits the form" : "presses a button"}]`).join(" → ")}
Intent: ${scenario.intent}

Interface:
${finalText || "(nothing was shown)"}`;
    let text = "";
    let usage: Usage | undefined;
    for await (const ev of provider.stream({
      model,
      system: SYSTEM,
      messages: [{ role: "user", content: user }],
      maxTokens: 400,
      ...(provider.capabilities?.constrainedOutput ? { responseSchema: SCHEMA } : {}),
    })) {
      if (ev.type === "text") text += ev.delta;
      if (ev.type === "done") usage = ev.usage;
    }
    if (usage) onUsage?.(usage);
    const parsed = parseLenient(text) as { score?: unknown; reason?: unknown };
    const raw = Number(parsed.score);
    if (!Number.isFinite(raw) || raw < 1 || raw > 5) throw new Error(`judge gave no 1-5 score: ${text.slice(0, 120)}`);
    return { score: (raw - 1) / 4, reason: String(parsed.reason ?? ""), usage };
  };
}
